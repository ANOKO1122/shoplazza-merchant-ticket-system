import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import * as pg from './pg';
import * as installer from './protection-installer';
import { createStore } from './store-service';
import { createSession, seedAgent } from './auth';
import { seedProtectionStores, enqueueProtectionInstall, listProtectionStores, processProtectionInstallJobs, getProtectionInstallJob } from './protection-store-service';
import { createProtectionStoreRouter } from './protection-store-routes';

const testUrl = process.env.SUPPORT_PROTECTION_STORE_TEST_DATABASE_URL;
test('store actions serialize, retain failures, exclude credentials and enforce admin sessions', { skip: !testUrl, timeout:60_000 }, async t => {
  const url=new URL(testUrl!);
  assert.ok(['localhost','127.0.0.1','[::1]'].includes(url.hostname));
  assert.match(url.pathname,/^\/support_\w+_test$/);
  process.env.SUPPORT_DATABASE_URL=testUrl;
  process.env.SUPPORT_TOKEN_SECRET='isolated-test-key';
  t.after(pg.closeDatabasePools);
  assert.equal(Number((await pg.query("SELECT count(*) FROM pg_tables WHERE schemaname='public'")).rows[0].count),0);
  await pg.ensureTables();
  const known=await createStore({subdomain:'amao04',store_name:'Isolated fixture',access_token:'test-private-token'});
  const other=await createStore({subdomain:'fixture-unknown',access_token:'test-other-token'});
  await seedProtectionStores();
  const stores=await listProtectionStores();
  assert.equal(stores.find(s=>s.id===Number(known.id))!.configured,true);
  assert.equal(stores.find(s=>s.id===Number(other.id))!.configured,false);
  assert.ok(!JSON.stringify(stores).includes('test-private-token'));
  const actor={agentId:1,name:'Reviewer'};
  const attempts=await Promise.allSettled([enqueueProtectionInstall(Number(known.id),'check',actor),enqueueProtectionInstall(Number(known.id),'check',actor)]);
  assert.equal(attempts.filter(r=>r.status==='fulfilled').length,1);
  assert.equal((attempts.find(r=>r.status==='rejected') as PromiseRejectedResult).reason.status,409);
  const job=(attempts.find(r=>r.status==='fulfilled') as PromiseFulfilledResult<any>).value;
  let runs=0;
  const run: typeof installer.runProtectionInstaller = async (_domain, _action, manifest) => { runs++; return {manifest,result:{health:'healthy',message:'fixture verified',active_theme_id:manifest.themeId},error:null}; };
  await Promise.all([processProtectionInstallJobs(run),processProtectionInstallJobs(run)]);
  assert.equal(runs,1);
  assert.equal((await getProtectionInstallJob(job.id))!.status,'succeeded');
  await assert.rejects(enqueueProtectionInstall(Number(other.id),'install',actor),/适配/);
  const next=await enqueueProtectionInstall(Number(known.id),'check',actor);
  await processProtectionInstallJobs(async () => { throw Error('provider rejected test-private-token'); });
  const failed=(await getProtectionInstallJob(next.id))!;
  assert.equal(failed.status,'failed');
  assert.ok(!failed.message.includes('test-private-token'));

  await seedAgent({username:'admin-fixture',name:'Admin fixture',password:'fixture-only-password',role:'admin'});
  await seedAgent({username:'agent-fixture',name:'Agent fixture',password:'fixture-only-password',role:'agent'});
  const agents=(await pg.query('SELECT id,role FROM support_agents')).rows;
  const tokens=Object.fromEntries(await Promise.all(agents.map(async a=>[a.role,await createSession(a.id)])));
  const app=express(); app.use(express.json()); app.use('/api/admin/protection',createProtectionStoreRouter());
  const server=app.listen(0,'127.0.0.1'); await new Promise<void>(resolve=>server.once('listening',resolve));
  t.after(()=>new Promise<void>(resolve=>{server.closeAllConnections();server.close(()=>resolve());}));
  const base=`http://127.0.0.1:${(server.address() as any).port}/api/admin/protection`;
  assert.equal((await fetch(base+'/stores')).status,401);
  const post=(role:string,origin?:string)=>fetch(base+`/stores/${known.id}/actions`,{method:'POST',headers:{'Content-Type':'application/json',Cookie:'support_session='+tokens[role],Origin:origin || new URL(base).origin},body:JSON.stringify({action:'check'})});
  assert.equal((await post('agent')).status,403);
  assert.equal((await post('admin','https://foreign.invalid')).status,403);
  assert.equal((await post('admin')).status,202);
  const response=await fetch(base+'/stores',{headers:{Cookie:'support_session='+tokens.agent}});
  assert.equal(response.status,200);
  assert.ok(!(await response.text()).includes('test-private-token'));
});
